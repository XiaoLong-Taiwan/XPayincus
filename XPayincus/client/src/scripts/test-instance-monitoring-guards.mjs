import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const read = (path) => readFileSync(new URL(path, import.meta.url), 'utf8')
const api = read('../api/agent-monitoring.ts')
const composable = read('../composables/useInstanceMonitoring.ts')
const panel = read('../components/instances/InstanceMonitoringPanel.vue')
const network = read('../components/instances/InstanceNetworkInfo.vue')
const detail = read('../views/InstanceDetailView.vue')

assert.match(api, /instanceMonitoringStreamUrl/)
assert.match(api, /createInstanceMonitoringStreamTicket/)
assert.match(api, /http\.post\(`\/instances\/\$\{instanceId\}\/monitoring\/stream-ticket`/)
assert.match(api, /url\.searchParams\.set\('ticket', ticket\)/)
assert.doesNotMatch(api, /searchParams\.set\('token'/)
assert.match(composable, /new EventSource/)
assert.match(composable, /attempt !== connectionAttempt/)
assert.match(composable, /MAX_RECONNECT_ATTEMPTS = 5/)
assert.match(composable, /2 \*\* \(reconnectAttempt\.value - 1\)/)
assert.match(composable, /MAX_TREND_POINTS = 100/)
assert.match(composable, /7 \* 86400000/)
assert.match(composable, /status\.value = 'offline'/)
assert.match(panel, /cpuUsagePercent/)
assert.match(api, /rxBytesPerSecond/)
assert.match(api, /txBytesPerSecond/)
assert.match(panel, /rxBytesPerSecond/)
assert.match(panel, /txBytesPerSecond/)
assert.doesNotMatch(panel, /networkReceiveBytesPerSecond|networkTransmitBytesPerSecond/)
assert.match(panel, /memoryUsedBytes/)
assert.match(panel, /七日趨勢/)
assert.match(panel, /Agent 離線/)
assert.match(network, /instance\.ipv4/)
assert.match(network, /v-if="ipv6"/)
assert.match(network, /privatePort.*22/)
assert.match(network, /publicPort.*public_port/)
assert.match(detail, /InstanceMonitoringPanel/)
assert.match(detail, /connectInstanceMonitoring/)
assert.doesNotMatch(detail, /setInterval\(loadStats/)

console.log('instance monitoring guards passed')
