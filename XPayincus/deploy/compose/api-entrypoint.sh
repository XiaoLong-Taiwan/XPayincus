set -eu
set +x

for secret_name in postgres_password jwt_secret cookie_secret encryption_key admin_password; do
  if [ ! -r "/run/secrets/$secret_name" ] || [ ! -s "/run/secrets/$secret_name" ]; then
    printf 'Missing, unreadable or empty secret: %s\n' "$secret_name" >&2
    exit 1
  fi
done
JWT_SECRET="$(cat /run/secrets/jwt_secret)"
COOKIE_SECRET="$(cat /run/secrets/cookie_secret)"
ENCRYPTION_KEY="$(cat /run/secrets/encryption_key)"
ADMIN_PASSWORD="$(cat /run/secrets/admin_password)"
export JWT_SECRET COOKIE_SECRET ENCRYPTION_KEY ADMIN_PASSWORD
db_password="$(cat /run/secrets/postgres_password)"
case "$db_password" in
  ''|*[!a-f0-9]*) printf '%s\n' 'PostgreSQL password must be generated by panel.sh init (hex).' >&2; exit 1 ;;
esac
export DATABASE_URL="postgresql://incudal:${db_password}@db:5432/incudal"
unset db_password
chown node:node /opt/incudal/server/certs
chmod 700 /opt/incudal/server/certs
exec gosu node sh -eu -c 'pnpm exec prisma migrate deploy; exec node dist/app.js'
